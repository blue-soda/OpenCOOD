"""Single-car INT memory transfer with a PointPillars encoder and anchor heads.

Implements the author's in_box point-selection option, feature concatenation,
and weighted prediction-map feedback. The anchor adapter uses a learned
history-to-head projection. Age selects retained points; the four-field PFN
does not encode age. All feedback is generated by the detector itself.
"""
import argparse
import base64
import json
from pathlib import Path
import re

import numpy as np
import torch
from torch import nn

from opencood.data_utils.int_ego_stream import training_order, sha256
from opencood.data_utils.int_v2v_ego_stream import v2v_rows
from opencood.hypes_yaml.yaml_utils import load_yaml
from opencood.loss.point_pillar_dir_loss import PointPillarDirLoss
from opencood.models.point_pillar_int import PointPillarINT
from opencood.models.sub_modules.int_feature_memory import warp_bev
from opencood.tools.run_int_ego import freeze_bn_stats, loader, to_device, write_json
from opencood.tools.train_int_full_dair_pair import full_rows
from opencood.utils import eval_utils


def metadata(row):
    if 'pose' in row:
        return row
    # The V2V4Real YAML encodes a homogeneous float64 matrix as a NumPy tag.
    # Decode the bytes without constructing Python objects from annotation YAML.
    header = Path(row['annotation']).read_text().split('\nvehicles:', 1)[0]
    section = re.search(r'^lidar_pose:.*?(?=^\w+:|\Z)', header, re.M | re.S)
    if section is None:
        raise ValueError(('missing lidar_pose', row['annotation']))
    payload = re.findall(r'!!binary \|\s*\n((?:[ \t]+[A-Za-z0-9+/=]+[ \t]*\n?)+)', section.group())
    pose = np.frombuffer(base64.b64decode(payload[-1]), dtype='<f8').reshape(4, 4)
    if not (np.allclose(pose[3], [0, 0, 0, 1]) and
            np.allclose(pose[:3, :3].T @ pose[:3, :3], np.eye(3), atol=1e-5)):
        raise ValueError(('invalid rigid pose', row['annotation']))
    return dict(row, pose=pose.tolist(), timestamp_us=int(row['source_frame']) * 100000)


def current_points(processed):
    voxels = processed['voxel_features']
    valid = torch.arange(voxels.shape[1], device=voxels.device)[None, :] < processed['voxel_num_points'][:, None]
    return voxels[valid].detach().cpu().numpy()


def align_points(history, old_pose, new_pose, dt):
    points = history[history[:, 4] + dt <= 10.0].copy()
    transform = np.linalg.solve(new_pose, old_pose)
    points[:, :3] = points[:, :3] @ transform[:3, :3].T + transform[:3, 3]
    points[:, 4] += dt
    return points


def update_points(past, current, boxes, rng):
    selected = np.zeros(len(current), dtype=bool)
    if boxes is not None:
        for box in boxes.detach().cpu().numpy():
            xyz = current[:, :3]
            near = np.flatnonzero(((xyz >= box.min(0)) & (xyz <= box.max(0))).all(1))
            if len(near):
                edges = box[[1, 3, 4]] - box[0]
                proj = (xyz[near] - box[0]) @ edges.T
                selected[near] |= ((proj >= 0) & (proj <= (edges * edges).sum(1))).all(1)
    indices = np.flatnonzero(selected)
    if len(indices) > 5000:
        indices = rng.choice(indices, 5000, replace=False)
    if len(past) + len(indices) > 50000:
        past = past[rng.choice(len(past), 50000-len(indices), replace=False)]
    fresh = np.zeros((len(indices), 5), dtype=np.float32)
    fresh[:, :4] = current[indices]
    return np.concatenate([past, fresh]), len(indices)


class StreamINT(nn.Module):
    def __init__(self, cfg, weights, arm):
        super().__init__()
        self.detector = PointPillarINT(cfg['model']['args'], 'single' if arm == 'single' else 'concat')
        self.detector.load_single_checkpoint(weights)
        self.full_memory = arm == 'three'
        self.use_points = self.full_memory
        self.use_map = self.full_memory
        self.bounds = cfg['preprocess']['cav_lidar_range']
        if self.full_memory:
            d = self.detector
            channels = d.cls_head.out_channels + d.reg_head.out_channels + d.dir_head.out_channels
            self.map_to_feature = nn.Conv2d(channels, d.out_channel, 1, bias=False)
            nn.init.zeros_(self.map_to_feature.weight)

    def step(self, ego, row, state, ds):
        reset = state is None or row['reset_before'] or state['segment'] != row['segment']
        if reset:
            state = None
        d = self.detector
        prev = None if state is None else state['fm']
        if state is not None:
            assert state['segment'] == row['segment'] and 0 < row['timestamp_us']-state['time'] <= 250000
        processed = ego['processed_lidar']
        if self.use_points:
            current = current_points(processed)
            past = np.zeros((0, 5), dtype=np.float32)
            if state is not None:
                dt = (row['timestamp_us'] - state['time']) / 1e6
                past = align_points(state['pc'], state['pose'], row['pose'], dt)
            if len(past):
                joined = np.concatenate([current, past[:, :4]])
                processed = to_device(ds.pre.collate_batch([ds.pre.preprocess(joined)]), d.cls_head.weight.device)
        features = {k:processed[k] for k in ('voxel_features','voxel_coords','voxel_num_points')}
        features['batch_size'] = 1
        if len(features['voxel_features']):
            spatial = d.scatter(d.pillar_vfe(features))['spatial_features']
        else:
            nx, ny, _ = d.scatter.model_cfg['grid_size']
            spatial = d.cls_head.weight.new_zeros(1, 64, int(ny), int(nx))
        spatial, fm, _ = d.feature_memory.step(spatial, prev, row)
        feat = d.backbone({'spatial_features':spatial})['spatial_features_2d']
        if d.shrink_flag:
            feat = d.shrink_conv(feat)
        hm = None
        if self.use_map and state is not None:
            hm, _ = warp_bev(state['hm'], state['pose'], row['pose'], self.bounds, mode='bilinear')
            feat = feat + self.map_to_feature(hm)
        pred = dict(psm=d.cls_head(feat), rm=d.reg_head(feat), dm=d.dir_head(feat))
        nxt = dict(fm=fm, pose=row['pose'], segment=row['segment'], time=row['timestamp_us'])
        diag = dict(pc_read=0, pc_added=0, map_read=hm is not None, reset=bool(reset))
        if self.use_map:
            with torch.no_grad():
                values = torch.cat([pred[k].detach() for k in ('psm','rm','dm')], dim=1)
                nxt['hm'] = values if hm is None else .5 * (values + hm)
        if self.use_points:
            with torch.no_grad():
                boxes, _ = ds.post.post_process({'ego':ego}, {'ego':pred})
                nxt['pc'], added = update_points(past, current, boxes, np.random.RandomState(303+int(row['frame'])))
                diag.update(pc_read=len(past), pc_added=added)
        return pred, nxt, diag


def run_epoch(net, rows, cfg, out, opt, criterion):
    training = opt is not None
    net.train(training)
    freeze_bn_stats(net)
    ds, stream = loader(rows, cfg, 2, 303)
    stats = {t:dict(tp=[], fp=[], gt=0, score=[]) for t in (.5,.7)}
    losses, state, linked, point_reads, adds, map_grad = [], None, 0, 0, 0, 0.
    with out.with_suffix('.jsonl').open('x', buffering=1) as log, torch.set_grad_enabled(training):
        for sample in stream:
            row = metadata(sample['meta'])
            assert sample['ego'] is not None
            ego = to_device(sample['ego'], torch.device('cuda'))
            pred, state, diag = net.step(ego, row, state, ds)
            linked += int(diag['map_read'])
            adds += diag['pc_added']
            point_reads += diag['pc_read']
            rec = dict(scene=row['scene'], frame=row['frame'], **diag)
            if row['supervised']:
                if training:
                    opt.zero_grad()
                    loss = criterion(pred, ego['label_dict'])
                    loss.backward()
                    grad = nn.utils.clip_grad_norm_(net.parameters(), 10.)
                    if not torch.isfinite(loss) or not torch.isfinite(grad):
                        raise FloatingPointError(row['frame'])
                    if net.full_memory and net.map_to_feature.weight.grad is not None:
                        map_grad = max(map_grad,float(net.map_to_feature.weight.grad.norm()))
                    opt.step()
                    losses.append(float(loss.detach()))
                    rec.update(loss=losses[-1], grad=float(grad))
                else:
                    boxes, confidence = ds.post.post_process({'ego':ego}, {'ego':pred})
                    gt = ds.post.generate_gt_bbx({'ego':ego})
                    per = {t:dict(tp=[],fp=[],gt=0,score=[]) for t in stats}
                    for t in stats:
                        eval_utils.caluclate_tp_fp(boxes,confidence,gt,per,t)
                        for k in stats[t]:
                            stats[t][k] += per[t][k]
                    rec.update(ap70=per[.7], ap50=per[.5])
            log.write(json.dumps(rec)+'\n')
    if net.use_map:
        assert linked and (not training or map_grad > 0)
    if net.use_points:
        assert adds and point_reads
    summary = dict(scans=len(rows),labels=sum(r['supervised'] for r in rows),past_map_frames=linked,
                   past_point_reads=point_reads,foreground_additions=adds, max_map_projection_gradient=map_grad)
    if training:
        assert len(losses) == summary['labels']
        summary['mean_loss'] = float(np.mean(losses))
    else:
        summary.update(ap50=eval_utils.calculate_ap(stats,.5)[0],ap70=eval_utils.calculate_ap(stats,.7)[0],gt=stats[.7]['gt'])
    write_json(out.with_suffix('.json'), summary)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for name in ('root','datasets','out'):
        p.add_argument(name, type=Path)
    p.add_argument('arm', choices=('fm','three','single'))
    p.add_argument('--v2v', type=Path)
    p.add_argument('--v2v-dataset-root',type=Path)
    p.add_argument('--order-seed',type=int,default=303,help='Change clip order only, preserving model and point-sampling initialization.')
    p.add_argument('--pilot', action='store_true')
    p.add_argument('--eval-checkpoint', type=Path)
    p.add_argument('--eval-history', type=int, default=0, help='0 means the full contiguous segment')
    p.add_argument('--omit', choices=('point','map'), help='Frozen evaluation intervention')
    args = p.parse_args()
    if args.eval_history < 0 or (args.omit and (not args.eval_checkpoint or args.arm != 'three')):
        p.error('Invalid evaluation intervention')
    args.out.mkdir(parents=True, exist_ok=False)
    torch.manual_seed(303)
    torch.backends.cudnn.deterministic = True
    torch.backends.cudnn.benchmark = False
    torch.backends.cuda.matmul.allow_tf32 = torch.backends.cudnn.allow_tf32 = False
    weights = args.root/'external_int556/p1.pth'
    assert sha256(weights) == 'c5fdef2fcc2914a09bb527cee6723730e70850056e3115f3197122e69431efb9'
    cfg = load_yaml(str(args.root/'inputs/config.yaml'))
    cfg['data_augment'] = []
    manifest = args.v2v or args.root/'sequence_manifest.json'
    train,val = [v2v_rows(manifest, split,args.v2v_dataset_root) if args.v2v else full_rows(manifest,args.datasets,split) for split in ('train','val')]
    net = StreamINT(cfg,torch.load(weights,map_location='cpu'),args.arm).cuda()
    opt = torch.optim.AdamW(net.parameters(),lr=1e-4,weight_decay=1e-4)
    criterion = PointPillarDirLoss(cfg['loss']['args']).cuda()
    epochs = 1 if args.pilot else 2
    write_json(args.out/'contract.json', dict(arm=args.arm,manifest=sha256(manifest),p1=sha256(weights),
               pilot=args.pilot,epochs=epochs,seed=303,training_order_seed=args.order_seed,training_windows=[5,10][:epochs],
               evaluation_history=args.eval_history,omitted=args.omit,
               inference_map='anchor outputs, weighted recurrent map, bilinear metric warp',
               points='predicted in_box on retained PFN points; max 5000/frame, 50000 total, 10s; age outside PFN',
               deployment_parameters=sum(p.numel() for p in net.parameters())))
    if args.eval_checkpoint:
        net.load_state_dict(torch.load(args.eval_checkpoint,map_location='cpu'),strict=True)
        write_json(args.out/'evaluation_source.json',dict(checkpoint=str(args.eval_checkpoint),
                   sha256=sha256(args.eval_checkpoint)))
    else:
        for epoch in range(1,epochs+1):
            order = training_order(train,5*epoch,args.order_seed-1+epoch)
            run_epoch(net, order[:160] if args.pilot else order, cfg, args.out/('train_%02d'%epoch), opt, criterion)
            torch.save(net.state_dict(),str(args.out/('epoch_%02d.pt'%epoch)))
    if args.eval_history:
        age, last_segment = 0, None
        for row in val:
            if row['segment'] != last_segment or row['reset_before']:
                age = 0
            row['reset_before'] = age == 0
            age = (age+1) % args.eval_history
            last_segment = row['segment']
    if args.omit == 'map':
        net.use_map = False
    if args.omit == 'point':
        net.use_points = False
    run_epoch(net,val[:192] if args.pilot else val,cfg,args.out/'val',None,criterion)


if __name__ == '__main__':
    main()
